import React, { useState, useEffect, useCallback } from 'react';
import { wishesService } from '../../services/wishesService';
import { formatDate, truncateText } from '../../utils/formatters';
import { Card } from '../../components/ui/Card';
import { Badge } from '../../components/ui/Badge';
import { Button } from '../../components/ui/Button';
import { EmptyState } from '../../components/ui/EmptyState';
import { CardSkeleton } from '../../components/ui/Skeleton';
import { WishDetailModal } from './WishDetailModal';
import { useToast } from '../../components/ui/ToastContext';
import type { WishWithDetails } from '../../types';
import {
  Sparkles,
  Send,
  CheckCircle2,
  Clock,
  Search,
  MessageCircle,
  MessageSquare,
  Mail,
  Calendar,
  User,
  ArrowRight,
} from 'lucide-react';

export const WishesPage: React.FC = () => {
  const { error: toastError } = useToast();
  const [activeTab, setActiveTab] = useState<'pending' | 'sent'>('pending');
  const [wishes, setWishes] = useState<WishWithDetails[]>([]);
  const [isLoading, setIsLoading] = useState(true);
  const [search, setSearch] = useState('');
  const [selectedWish, setSelectedWish] = useState<WishWithDetails | null>(null);

  // Tab counts
  const [pendingCount, setPendingCount] = useState(0);
  const [sentCount, setSentCount] = useState(0);

  const fetchWishes = useCallback(async () => {
    setIsLoading(true);
    try {
      // Fetch both counts for tab badges
      const [pendingRes, sentRes] = await Promise.all([
        wishesService.getWishes({ isSent: false, limit: 1 }),
        wishesService.getWishes({ isSent: true, limit: 1 }),
      ]);
      setPendingCount(pendingRes.count);
      setSentCount(sentRes.count);

      // Fetch active list
      const res = await wishesService.getWishes({
        isSent: activeTab === 'sent',
        search,
        limit: 100,
      });
      setWishes(res.data);
    } catch (err: unknown) {
      console.error('Failed to fetch wishes:', err);
      toastError('Could not load wishes. Check Supabase connection.');
    } finally {
      setIsLoading(false);
    }
  }, [activeTab, search, toastError]);

  useEffect(() => {
    fetchWishes();
  }, [fetchWishes]);

  return (
    <div className="space-y-6">
      {/* Page Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-white tracking-tight flex items-center gap-2.5">
            <Sparkles className="w-6 h-6 text-indigo-400" />
            Wishes Hub
          </h1>
          <p className="text-xs sm:text-sm text-slate-400 mt-1">
            Personalized messages generated by n8n workflow for upcoming celebrations and milestones
          </p>
        </div>
      </div>

      {/* Tabs & Search Bar */}
      <div className="flex flex-col sm:flex-row items-stretch sm:items-center justify-between gap-3 p-2 bg-slate-900/60 border border-slate-800 rounded-2xl">
        {/* Tab Switcher */}
        <div className="flex items-center gap-1.5 p-1 bg-slate-950/80 rounded-xl">
          <button
            onClick={() => setActiveTab('pending')}
            className={`flex items-center gap-2 px-4 py-2 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
              activeTab === 'pending'
                ? 'bg-indigo-600 text-white shadow-md shadow-indigo-600/20'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            <Clock className="w-3.5 h-3.5" />
            <span>New Wishes</span>
            <span
              className={`px-1.5 py-0.5 rounded-full text-[10px] font-bold ${
                activeTab === 'pending' ? 'bg-indigo-700/80 text-white' : 'bg-slate-800 text-slate-400'
              }`}
            >
              {pendingCount}
            </span>
          </button>

          <button
            onClick={() => setActiveTab('sent')}
            className={`flex items-center gap-2 px-4 py-2 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
              activeTab === 'sent'
                ? 'bg-emerald-600 text-white shadow-md shadow-emerald-600/20'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            <CheckCircle2 className="w-3.5 h-3.5" />
            <span>Sent Wishes</span>
            <span
              className={`px-1.5 py-0.5 rounded-full text-[10px] font-bold ${
                activeTab === 'sent' ? 'bg-emerald-700/80 text-white' : 'bg-slate-800 text-slate-400'
              }`}
            >
              {sentCount}
            </span>
          </button>
        </div>

        {/* Search */}
        <div className="relative w-full sm:w-72">
          <Search className="w-4 h-4 absolute left-3.5 top-1/2 -translate-y-1/2 text-slate-400" />
          <input
            type="text"
            placeholder="Search wishes by name or event..."
            className="w-full bg-slate-950/70 border border-slate-800 focus:border-indigo-500 rounded-xl py-1.5 pl-10 pr-3 text-xs sm:text-sm text-slate-100 placeholder-slate-500 focus:outline-none focus:ring-1 focus:ring-indigo-500"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
          />
        </div>
      </div>

      {/* Wishes Grid */}
      {isLoading ? (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {Array.from({ length: 4 }).map((_, i) => (
            <CardSkeleton key={i} />
          ))}
        </div>
      ) : wishes.length === 0 ? (
        <EmptyState
          icon={
            activeTab === 'pending' ? (
              <Sparkles className="w-7 h-7 text-indigo-400" />
            ) : (
              <CheckCircle2 className="w-7 h-7 text-emerald-400" />
            )
          }
          title={
            activeTab === 'pending'
              ? search
                ? 'No matching pending wishes'
                : 'All caught up! No pending wishes'
              : search
              ? 'No matching sent wishes'
              : 'No wishes marked as sent yet'
          }
          description={
            activeTab === 'pending'
              ? ' '
              : ' '
          }
        />
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {wishes.map((wish) => {
            const person = wish.person;
            const event = wish.event;

            return (
              <Card
                key={wish.wish_id}
                hoverable
                onClick={() => setSelectedWish(wish)}
                className="cursor-pointer group flex flex-col justify-between border-slate-800 hover:border-indigo-500/40 transition-all"
              >
                <div>
                  {/* Top Bar on Card */}
                  <div className="flex items-start justify-between gap-3 mb-3">
                    <div className="flex items-center gap-3">
                      <div className="w-10 h-10 rounded-xl bg-indigo-950/70 border border-indigo-500/20 flex items-center justify-center text-indigo-300 font-bold text-sm shrink-0">
                        {person?.full_name ? person.full_name[0].toUpperCase() : 'U'}
                      </div>
                      <div className="overflow-hidden">
                        <div className="text-sm font-semibold text-white group-hover:text-indigo-300 transition-colors truncate">
                          {person?.full_name || 'Unknown Recipient'}
                        </div>
                        <div className="text-xs text-slate-400 flex items-center gap-1.5 truncate">
                          <Calendar className="w-3 h-3 text-indigo-400 shrink-0" />
                          <span className="truncate">
                            {event?.event_name || 'Event'} • {formatDate(event?.event_date)}
                          </span>
                        </div>
                      </div>
                    </div>

                    {wish.isSent ? (
                      <Badge variant="success" className="text-[11px] gap-1 shrink-0">
                        <CheckCircle2 className="w-3 h-3" /> Sent
                      </Badge>
                    ) : (
                      <Badge variant="warning" className="text-[11px] shrink-0">
                        New
                      </Badge>
                    )}
                  </div>

                  {/* Message Preview */}
                  <div className="p-3 rounded-xl bg-slate-950/70 border border-slate-800/80 my-3">
                    <p className="text-xs text-slate-300 line-clamp-3 leading-relaxed">
                      {wish.short_wish || wish.long_wish || wish.mail_wish?.subject || 'Wish generated and ready.'}
                    </p>
                  </div>

                  {/* Available Message Format Chips */}
                  <div className="flex items-center gap-2 text-[11px] text-slate-400">
                    <span className="text-[10px] uppercase font-semibold text-slate-400">
                      Formats:
                    </span>
                    {wish.long_wish && (
                      <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-md bg-emerald-950/40 border border-emerald-500/30 text-emerald-300">
                        <MessageCircle className="w-3 h-3" /> WhatsApp
                      </span>
                    )}
                    {wish.short_wish && (
                      <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-md bg-indigo-950/40 border border-indigo-500/30 text-indigo-300">
                        <MessageSquare className="w-3 h-3" /> SMS
                      </span>
                    )}
                    {wish.mail_wish && (
                      <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-md bg-sky-950/40 border border-sky-500/30 text-sky-300">
                        <Mail className="w-3 h-3" /> Email
                      </span>
                    )}
                  </div>
                </div>

                {/* Bottom Row */}
                <div className="flex items-center justify-between pt-3 mt-3 border-t border-slate-800/80 text-xs text-indigo-400 font-semibold group-hover:text-indigo-300">
                  <span className="text-slate-400 text-[11px] font-normal">
                    Created {formatDate(wish.created_at)}
                  </span>
                  <div className="flex items-center gap-1">
                    <span>{wish.isSent ? 'View Sent Details' : 'Review & Send'}</span>
                    <ArrowRight className="w-3.5 h-3.5 group-hover:translate-x-0.5 transition-transform" />
                  </div>
                </div>
              </Card>
            );
          })}
        </div>
      )}

      {/* Wish Detail & Sending Modal */}
      {selectedWish && (
        <WishDetailModal
          isOpen={Boolean(selectedWish)}
          wish={selectedWish}
          onClose={() => setSelectedWish(null)}
          onStatusChanged={() => {
            setSelectedWish(null);
            fetchWishes();
          }}
        />
      )}
    </div>
  );
};
